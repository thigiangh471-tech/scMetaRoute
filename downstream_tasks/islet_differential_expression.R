# Figure 4c: donor-blocked local-versus-rest pseudobulk for the frozen MC124 region.
args <- commandArgs(trailingOnly=TRUE)
if (length(args) != 3) stop("usage: Rscript islet_differential_expression.R paired_counts.tsv.gz paired_samples.tsv output.tsv")
suppressPackageStartupMessages(library(edgeR))
counts <- as.matrix(read.delim(gzfile(args[1]), row.names=1, check.names=FALSE))
samples <- read.delim(args[2], check.names=FALSE)
stopifnot(identical(samples$sample, colnames(counts)), all(counts == round(counts)), all(counts >= 0))
stopifnot(all(samples$cells >= 20), all(table(samples$donor_id, samples$region) == 1))
samples$donor_id <- factor(samples$donor_id)
samples$region <- factor(samples$region, levels=c("rest", "local"))
design <- model.matrix(~ donor_id + region, samples)
stopifnot(qr(design)$rank == ncol(design))
y <- DGEList(counts)
keep <- filterByExpr(y, design=design)
y <- calcNormFactors(y[keep, , keep.lib.sizes=TRUE])
y <- estimateDisp(y, design, robust=TRUE)
fit <- glmQLFit(y, design, robust=TRUE)
de <- topTags(glmQLFTest(fit, coef="regionlocal"), n=Inf, sort.by="none")$table
out <- data.frame(gene_id=rownames(counts), tested=keep)
out <- cbind(out, de[match(out$gene_id, rownames(de)), , drop=FALSE])
write.table(out, args[3], sep="\t", quote=FALSE, row.names=FALSE, na="NA")
